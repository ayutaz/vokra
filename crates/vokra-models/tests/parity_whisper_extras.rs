//! `whisper-extras` family — real-checkpoint parity harness.
//!
//! Covered models (both = Whisper large-v3 encoder + 2-layer decoder, same
//! shape quintuple `(d_model=1280, n_audio_layer=32, n_text_layer=2,
//! n_mels=128, vocab=51866)`; distinct upstream + license + arch tag):
//!
//! - **distil-whisper / distil-large-v3.5** (MIT / MIT) —
//!   [`vokra_models::distil_whisper::EXPECTED_ARCH`] = `"distil-whisper"`.
//! - **kotoba-tech / kotoba-whisper-v2.2** (Apache-2.0 / Apache-2.0) —
//!   [`vokra_models::kotoba_whisper::EXPECTED_ARCH`] = `"kotoba-whisper"`;
//!   architecturally identical to `-v2.0`, only distilled on a newer
//!   ReazonSpeech snapshot.
//!
//! # Gating (fabricated pass 禁止 — FR-EX-08)
//!
//! Every test is env-gated on `VOKRA_<ARCH>_GGUF` pointing at a
//! pre-converted GGUF (produced by `vokra-cli convert --model
//! {distil-whisper,kotoba-whisper-v2.2}` against a real HF snapshot at a
//! pinned revision — see the VAST runner under
//! `tools/parity/whisper_extras/run_vast_validation.sh`; the GitHub workflow
//! is deliberately model-free.
//! When the env var is unset, the test prints a clear skip reason and
//! returns — **never** a silent pass, **never** a synthesized substitute.
//!
//! `VOKRA_<ARCH>_REFDIR` is mandatory whenever a GGUF is supplied. It must be
//! an independent packet generated by
//! `tools/parity/whisper_extras/dump_reference.py` from the pinned Transformers
//! implementation. The test
//! compares the native CPU encoder, prefix logits, and greedy token sequence
//! against that packet; a missing or malformed packet is an error, never a
//! skip. The config-only constructors remain covered by model unit tests, but
//! are not a success condition for this real-weight harness.
//!
//! # What the test verifies today (real CPU parity)
//!
//! 1. `vokra.model.arch` string matches the expected canonical tag
//!    (distinct from vanilla Whisper's `"whisper"` — provenance / telemetry /
//!    model-card correctness), and authenticates the fixed source packet
//!    identity before running the native forward.
//! 2. Every `vokra.whisper.*` hparam the converter emits equals the
//!    primary-source config transcribed in the runtime module (a converter
//!    that started writing a different `n_text_layer` value than the runtime
//!    honors would silently break the distil axis — this test catches it).
//! 3. The distil invariant `n_text_layer < n_audio_layer` holds on both
//!    sides (converter output *and* the Rust config factory).
//! 4. At least one representative encoder + decoder tensor exists with the
//!    expected element count (byte-level sanity on the shape flow — a
//!    zero-tensor GGUF would still pass steps 1-3 but is caught here).
//! 5. Native CPU encoder states, decoder prefix logits, and greedy generated
//!    token ids match the independent reference within the fixed FP32 bound.
//!
//! # What the test explicitly does NOT do
//!
//! - It does not run model execution when either env var is absent. This is a
//!   deliberate gated skip for ordinary local/PR runs; the real run belongs on
//!   VAST and requires both paths.
//!
//! # Reference packet contract
//!
//! The packet is intentionally small: real PCM, the first 32 encoder rows,
//! last-position prefix logits, and the greedy suffix. Its manifest pins the
//! upstream repo/revision, reference library versions, input hash, shapes,
//! decode language/task/no-timestamps semantics, metadata-file hashes, and
//! hashes for every binary file. Kotoba v2.2 must use the exact Japanese
//! prefix `[50258, 50266, 50360, 50364]`; the older family aliases are not
//! silently reinterpreted.

