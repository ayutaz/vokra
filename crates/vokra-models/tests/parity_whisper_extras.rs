/// One `vokra.whisper.*` hparam pair (key + expected `u32` value) the
/// converter writes deterministically from the checkpoint shapes.
struct HparamExpectation {
    key: &'static str,
    expected: u32,
    human_name: &'static str,
}

/// Reads a `u32`-valued metadata entry, panicking loudly (with the key name)
/// if it is missing or of the wrong type. Loud panics here are the whole
/// point: a converter that started writing `n_text_layer` as `I32` instead
/// of `U32` would silently break the runtime, so we refuse to guess.
fn expect_u32(gguf: &GgufFile, key: &str) -> u32 {
    let raw = gguf
        .get(key)
        .unwrap_or_else(|| panic!("GGUF is missing required metadata key `{key}`"));
    let widened = raw.as_u64().unwrap_or_else(|| {
        panic!(
            "GGUF metadata key `{key}` is not an unsigned int (got {:?})",
            raw.value_type()
        )
    });
    u32::try_from(widened)
        .unwrap_or_else(|_| panic!("GGUF metadata key `{key}` = {widened} does not fit into u32"))
}

/// Reads a `String`-valued metadata entry, panicking with the key name on
/// absence or wrong type.
fn expect_string<'a>(gguf: &'a GgufFile, key: &str) -> &'a str {
    let raw = gguf
        .get(key)
        .unwrap_or_else(|| panic!("GGUF is missing required metadata key `{key}`"));
    raw.as_str().unwrap_or_else(|| {
        panic!(
            "GGUF metadata key `{key}` is not a String (got {:?})",
            raw.value_type()
        )
    })
}

/// Verifies each hparam pair. On mismatch, panics with a message that names
/// the human-readable axis, the observed value, and the expected value.
fn verify_hparams(gguf: &GgufFile, pairs: &[HparamExpectation]) {
    for h in pairs {
        let got = expect_u32(gguf, h.key);
        assert_eq!(
            got, h.expected,
            "GGUF `{}` ({}) = {got}, expected {} — a converter that emits a \
             different value than the runtime module transcribes silently breaks \
             the distil axis; refusing to compare",
            h.key, h.human_name, h.expected,
        );
    }
}

/// Confirms a tensor exists at `name` and its element count equals the
/// expected product. Dtype is intentionally not pinned (F16 / F32 / BF16
/// pass-through are all valid per the converter's rules; the runtime binds
/// through the same dequant path regardless).
fn expect_tensor_elements(gguf: &GgufFile, name: &str, expected_elements: u64) {
    let info = gguf.tensor_info(name).unwrap_or_else(|| {
        panic!(
            "GGUF is missing required tensor `{name}` (a zero-tensor / \
             metadata-only GGUF would still pass metadata sanity but fail here)"
        )
    });
    let got = info
        .element_count()
        .unwrap_or_else(|e| panic!("tensor `{name}`: element_count overflow: {e:?}"));
    assert_eq!(
        got, expected_elements,
        "tensor `{name}` element_count = {got}, expected {expected_elements} \
         (dims stored innermost-first: {:?})",
        info.dimensions,
    );
}

fn read_f32(path: &Path) -> Vec<f32> {
    let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("read {path:?}: {e}"));
    assert!(
        bytes.len().is_multiple_of(4),
        "{path:?}: truncated f32 packet"
    );
    bytes
        .chunks_exact(4)
        .map(|b| f32::from_le_bytes(b.try_into().expect("f32 bytes")))
        .collect()
}

fn read_u32(path: &Path) -> Vec<u32> {
    let bytes = std::fs::read(path).unwrap_or_else(|e| panic!("read {path:?}: {e}"));
    assert!(
        bytes.len().is_multiple_of(4),
        "{path:?}: truncated u32 packet"
    );
    bytes
        .chunks_exact(4)
        .map(|b| u32::from_le_bytes(b.try_into().expect("u32 bytes")))
        .collect()
}

fn manifest_usize(root: &vokra_core::json::JsonValue, key: &str) -> usize {
    root.get(key)
        .and_then(vokra_core::json::JsonValue::as_u64)
        .and_then(|n| usize::try_from(n).ok())
        .unwrap_or_else(|| panic!("reference manifest `{key}` must be a usize"))
}

fn manifest_u32s(root: &vokra_core::json::JsonValue, key: &str) -> Vec<u32> {
    root.get(key)
        .and_then(vokra_core::json::JsonValue::as_array)
        .unwrap_or_else(|| panic!("reference manifest `{key}` must be an array"))
        .iter()
        .map(|v| {
            v.as_u64()
                .and_then(|n| u32::try_from(n).ok())
                .unwrap_or_else(|| panic!("reference manifest `{key}` contains a non-u32"))
        })
        .collect()
}

fn manifest_string<'a>(root: &'a vokra_core::json::JsonValue, key: &str) -> &'a str {
    root.get(key)
        .and_then(vokra_core::json::JsonValue::as_str)
        .unwrap_or_else(|| panic!("reference manifest `{key}` must be a string"))
}

fn manifest_f32(root: &vokra_core::json::JsonValue, key: &str) -> f32 {
    match root.get(key) {
        Some(vokra_core::json::JsonValue::Float(value)) => *value as f32,
        Some(vokra_core::json::JsonValue::Int(value)) => *value as f32,
        _ => panic!("reference manifest `{key}` must be a number"),
    }
}

fn manifest_bool(root: &vokra_core::json::JsonValue, key: &str) -> bool {
    match root.get(key) {
        Some(vokra_core::json::JsonValue::Bool(value)) => *value,
        _ => panic!("reference manifest `{key}` must be a boolean"),
    }
}

fn assert_manifest_sha256(root: &vokra_core::json::JsonValue, key: &str) {
    let value = manifest_string(root, key);
    assert_eq!(
        value.len(),
        64,
        "reference manifest `{key}` must be SHA-256"
    );
    assert!(
        value.bytes().all(|byte| byte.is_ascii_hexdigit()),
        "reference manifest `{key}` must contain hexadecimal SHA-256"
    );
}

fn sha256_file(path: &Path) -> String {
    for program in ["sha256sum", "shasum"] {
        let output = if program == "shasum" {
            Command::new(program).args(["-a", "256"]).arg(path).output()
        } else {
            Command::new(program).arg(path).output()
        };
        if let Ok(output) = output {
            if output.status.success() {
                if let Some(hash) = String::from_utf8_lossy(&output.stdout)
                    .split_whitespace()
                    .next()
                {
                    if hash.len() == 64 && hash.bytes().all(|b| b.is_ascii_hexdigit()) {
                        return hash.to_owned();
                    }
                }
            }
        }
    }
    panic!("no usable sha256 utility available for reference packet {path:?}");
}

/// Require the complete independent packet before any model forward. A
/// partially copied directory is a hard error, never a clean parity skip.
fn parse_reference_packet(member: &FamilyMember, refdir: &Path) -> vokra_core::json::JsonValue {
    assert!(
        refdir.is_dir(),
        "VOKRA_{}_REFDIR = {refdir:?} does not exist or is not a directory",
        member.arch_slug.to_ascii_uppercase(),
    );
    let path = refdir.join("manifest.json");
    let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {path:?}: {e}"));
    let root = vokra_core::json::parse(&bytes).unwrap_or_else(|e| panic!("parse {path:?}: {e}"));
    assert_eq!(manifest_string(&root, "schema"), REFERENCE_SCHEMA);
    assert_eq!(manifest_string(&root, "model"), member.arch_slug);
    assert_eq!(
        manifest_string(&root, "upstream_repo"),
        member.upstream_repo
    );
    assert_eq!(
        manifest_string(&root, "upstream_revision"),
        member.upstream_revision,
        "reference packet upstream revision drift"
    );
    assert_eq!(
        manifest_string(&root, "weight_license_spdx"),
        member.weight_license_spdx
    );
    assert_eq!(
        manifest_string(&root, "reference_implementation"),
        "transformers.WhisperForConditionalGeneration",
        "reference must come from the independent Transformers implementation"
    );
    assert_eq!(
        manifest_usize(&root, "checkpoint_bytes"),
        member.checkpoint_bytes,
        "checkpoint byte identity drift"
    );
    assert_eq!(
        manifest_string(&root, "checkpoint_sha256"),
        member.checkpoint_sha256,
        "checkpoint SHA-256 identity drift"
    );
    assert_eq!(
        manifest_usize(&root, "config_bytes"),
        member.config_bytes,
        "config byte identity drift"
    );
    assert_eq!(
        manifest_string(&root, "config_sha256"),
        member.config_sha256,
        "config SHA-256 identity drift"
    );
    assert_eq!(
        manifest_usize(&root, "generation_config_bytes"),
        member.generation_config_bytes,
        "generation_config byte identity drift"
    );
    assert_eq!(
        manifest_string(&root, "generation_config_sha256"),
        member.generation_config_sha256,
        "generation_config SHA-256 identity drift"
    );
    assert_eq!(
        manifest_usize(&root, "tokenizer_bytes"),
        member.tokenizer_bytes,
        "tokenizer byte identity drift"
    );
    assert_eq!(
        manifest_string(&root, "tokenizer_sha256"),
        member.tokenizer_sha256,
        "tokenizer SHA-256 identity drift"
    );
    for name in [
        "input_pcm.f32le",
        "encoder.f32le",
        "logits_last.f32le",
        "greedy_tokens.u32le",
    ] {
        let file = refdir.join(name);
        assert!(file.is_file(), "reference packet missing {file:?}");
        let expected = root
            .get("files")
            .and_then(vokra_core::json::JsonValue::as_object)
            .and_then(|entries| entries.iter().find(|(key, _)| key == name))
            .and_then(|(_, value)| value.as_str())
            .unwrap_or_else(|| panic!("reference manifest missing files.{name}"));
        assert_eq!(
            sha256_file(&file),
            expected,
            "reference packet hash drift: {name}"
        );
    }
    assert_eq!(manifest_usize(&root, "sample_rate"), 16_000);
    assert_eq!(
        manifest_string(&root, "audio_sha256"),
        INPUT_AUDIO_SHA256,
        "reference audio SHA-256 must match the fixed parity input"
    );
    assert_eq!(
        manifest_usize(&root, "pcm_samples"),
        INPUT_PCM_SAMPLES,
        "reference audio must be exactly 30 seconds at 16 kHz"
    );
    assert_eq!(
        manifest_f32(&root, "atol"),
        FP32_ATOL,
        "FP32_ATOL=0.01 is the preregistered existing Whisper-family bound, not a new measured result"
    );
    assert_manifest_sha256(&root, "generation_config_sha256");
    assert_manifest_sha256(&root, "tokenizer_sha256");
    let pcm = read_f32(&refdir.join("input_pcm.f32le"));
    let encoder = read_f32(&refdir.join("encoder.f32le"));
    let logits = read_f32(&refdir.join("logits_last.f32le"));
    let tokens = read_u32(&refdir.join("greedy_tokens.u32le"));
    assert_eq!(manifest_usize(&root, "pcm_samples"), pcm.len());
    assert!(
        manifest_usize(&root, "pcm_samples") > 0,
        "reference PCM is empty"
    );
    assert!(
        pcm.iter().all(|value| value.is_finite()),
        "reference PCM is non-finite"
    );

    let rows = manifest_usize(&root, "encoder_rows");
    let d_model = manifest_usize(&root, "d_model");
    let encoder_len = rows
        .checked_mul(d_model)
        .unwrap_or_else(|| panic!("reference encoder_rows*d_model overflows usize"));
    assert!(rows > 0, "reference encoder_rows must be non-zero");
    assert!(d_model > 0, "reference d_model must be non-zero");
    assert_eq!(
        encoder.len(),
        encoder_len,
        "reference encoder byte length drift"
    );
    assert!(
        encoder.iter().all(|value| value.is_finite()),
        "reference encoder contains non-finite values"
    );

    let vocab = manifest_usize(&root, "vocab");
    assert!(vocab > 0, "reference vocab must be non-zero");
    assert_eq!(logits.len(), vocab, "reference logits byte length drift");
    assert!(
        logits.iter().all(|value| value.is_finite()),
        "reference logits contain non-finite values"
    );

    let manifest_prefix = manifest_u32s(&root, "decoder_prefix");
    assert!(
        !manifest_prefix.is_empty(),
        "reference decoder prefix is empty"
    );
    let manifest_tokens = manifest_u32s(&root, "greedy_tokens");
    assert!(
        !manifest_tokens.is_empty(),
        "reference greedy token sequence is empty"
    );
    assert_eq!(
        tokens, manifest_tokens,
        "greedy token binary disagrees with manifest"
    );
    let eot = manifest_usize(&root, "eot");
    assert!(eot <= u32::MAX as usize, "reference eot does not fit u32");
    assert!(eot < vocab, "reference eot is outside manifest vocabulary");
    assert!(
        manifest_prefix
            .iter()
            .all(|&token| token as usize < vocab),
        "reference decoder prefix contains a token outside manifest vocabulary"
    );
    assert_eq!(
        manifest_string(&root, "language"),
        member.language,
        "reference language semantics drift"
    );
    assert_eq!(
        manifest_string(&root, "task"),
        member.task,
        "reference task semantics drift"
    );
    assert_eq!(
        manifest_bool(&root, "no_timestamps"),
        member.no_timestamps,
        "reference timestamp semantics drift"
    );
    assert_eq!(
        manifest_prefix, member.decoder_prefix,
        "reference decoder prefix must match the authenticated model contract"
    );
    assert!(
        manifest_tokens.iter().any(|&token| token as usize == eot),
        "reference greedy sequence never emits manifest eot"
    );
    assert!(
        manifest_tokens
            .iter()
            .all(|&token| token as usize < vocab),
        "reference greedy sequence contains a token outside manifest vocabulary"
    );
    assert!(
        manifest_tokens.len() <= 224,
        "reference greedy sequence exceeds MAX_NEW_TOKENS=224"
    );
    for (name, item_size, item_count) in [
        ("input_pcm.f32le", 4usize, pcm.len()),
        ("encoder.f32le", 4usize, encoder.len()),
        ("logits_last.f32le", 4usize, logits.len()),
        ("greedy_tokens.u32le", 4usize, tokens.len()),
    ] {
        let expected_bytes = item_count
            .checked_mul(item_size)
            .unwrap_or_else(|| panic!("reference {name} byte length overflows usize"));
        assert_eq!(
            std::fs::metadata(refdir.join(name))
                .unwrap_or_else(|e| panic!("stat reference {name}: {e}"))
                .len(),
            expected_bytes as u64,
            "reference {name} byte length drift"
        );
    }
    root
}

fn assert_close(actual: &[f32], expected: &[f32], label: &str) {
    assert_eq!(actual.len(), expected.len(), "{label}: length mismatch");
    assert!(
        actual.iter().all(|value| value.is_finite())
            && expected.iter().all(|value| value.is_finite()),
        "{label}: non-finite value"
    );
    let (index, max_abs) = actual
        .iter()
        .zip(expected)
        .enumerate()
        .map(|(i, (a, b))| (i, (a - b).abs()))
        .max_by(|a, b| a.1.total_cmp(&b.1))
        .expect("non-empty reference vector");
    eprintln!(
        "[parity_whisper_extras] {label}: max |Δ|={max_abs:.9e} at {index}, atol={FP32_ATOL:.3e}"
    );
    assert!(
        max_abs <= FP32_ATOL,
        "{label}: max |Δ|={max_abs:.9e} at {index} exceeds {FP32_ATOL}"
    );
}

fn run_real_cpu_parity(member: &FamilyMember, file: &GgufFile, refdir: &Path) {
    let root = parse_reference_packet(member, refdir);
    let pcm = read_f32(&refdir.join("input_pcm.f32le"));
    let encoder_reference = read_f32(&refdir.join("encoder.f32le"));
    let logits_reference = read_f32(&refdir.join("logits_last.f32le"));
    let token_reference = read_u32(&refdir.join("greedy_tokens.u32le"));
    let model = Arc::new(WhisperModel::from_gguf(file).expect("bind real Whisper weights"));
    let encoder = model.encode_pcm(&pcm).expect("native CPU encoder");
    let rows = manifest_usize(&root, "encoder_rows");
    let width = model.config().d_model;
    assert_eq!(width, manifest_usize(&root, "d_model"));
    assert!(
        rows <= model.config().n_audio_ctx,
        "reference encoder_rows={rows} exceeds model encoder context {}",
        model.config().n_audio_ctx
    );
    assert_eq!(
        model.config().n_vocab,
        manifest_usize(&root, "vocab"),
        "model config vocab disagrees with reference manifest"
    );
    assert_eq!(
        model.config().eot as usize,
        manifest_usize(&root, "eot"),
        "model config eot disagrees with reference manifest"
    );
    let native_len = rows
        .checked_mul(width)
        .unwrap_or_else(|| panic!("native encoder rows*d_model overflows usize"));
    assert!(
        encoder.hidden.len() >= native_len,
        "native encoder output is shorter than reference row bound"
    );
    assert_close(
        &encoder.hidden[..native_len],
        &encoder_reference,
        "encoder hidden",
    );

    let prefix = manifest_u32s(&root, "decoder_prefix");
    assert!(!prefix.is_empty(), "reference decoder prefix is empty");
    assert_eq!(
        model.config().decoder_start_ids,
        prefix,
        "decoder prefix drift"
    );
    assert_eq!(
        model.config().decoder_start_ids.as_slice(),
        member.decoder_prefix,
        "native decoder prefix is not the authenticated model contract"
    );
    let mut decoder = model.decoder(&encoder).expect("native CPU decoder");
    let logits = decoder.step(&prefix).expect("native CPU prefix logits");
    let vocab = model.config().n_vocab;
    assert_eq!(
        logits.len(),
        prefix.len() * vocab,
        "native prefix logits shape drift"
    );
    let last = &logits[(prefix.len() - 1) * vocab..];
    assert_close(last, &logits_reference, "decoder prefix last logits");

    match member.arch_slug {
        "distil_whisper" => {
            let asr = vokra_models::distil_whisper::DistilWhisperAsr::from_gguf(file)
                .expect("bind distil-whisper real weights");
            assert_eq!(
                asr.transcribe(&pcm).expect("native distil transcription"),
                token_reference
            );
        }
        "kotoba_whisper" => {
            let asr = vokra_models::kotoba_whisper::KotobaWhisperAsr::from_gguf(file)
                .expect("bind kotoba-whisper real weights");
            assert_eq!(
                asr.transcribe(&pcm).expect("native kotoba transcription"),
                token_reference
            );
        }
        other => panic!("unregistered whisper-extras member {other}"),
    }
}

