//! Xiph RNNoise v0.2 numerical parity harness — env-gated (denoise
//! tier, 2026-08-09 loud-partial forwards wave).
//!
//! Sibling of `parity_rmvpe.rs` / `parity_openwakeword.rs` /
//! `parity_dnsmos.rs`: every test that needs the RNNoise v0.2 GGUF is
//! gated on the [`GGUF_ENV`] environment variable and skips cleanly when
//! unset (never a fabricated pass, memory
//! `[[project-real-weight-eval]]` pattern). Once opted in, every failure
//! is hard: a missing / malformed / wrong-shaped fixture is a loud
//! panic (FR-EX-08).
//!
//! # Fixture recipe (owner-side)
//!
//! Upstream v0.2 embeds 36 trained arrays in `src/rnnoise_data.c` inside
//! the official release tarball. Bridge it to safetensors with the strict
//! `tools/parity/rnnoise_prepare_checkpoint.py` parser, then convert to GGUF:
//!
//! ```text
//! # 1. Fetch upstream v0.2 release tarball from
//! #    github.com/xiph/rnnoise/releases/tag/v0.2
//! # 2. Flatten to safetensors (offline, in a uv-managed venv):
//! uv run python tools/parity/rnnoise_prepare_checkpoint.py \
//!     --input  ~/rnnoise-v0.2/rnnoise-0.2.tar.gz \
//!     --output ~/rnnoise-v02.safetensors
//! # 3. Convert to GGUF:
//! vokra-cli convert --model rnnoise-v0.2 \
//!     --input  ~/rnnoise-v02.safetensors \
//!     --output ~/rnnoise-v02.gguf
//! # 4. Point the parity harness at it:
//! export VOKRA_RNNOISE_V02_REAL_GGUF=~/rnnoise-v02.gguf
//! cargo test -p vokra-models --test parity_rnnoise_v02 -- --nocapture
//! # The still-pending waveform/pitch tier uses a separate explicit opt-in:
//! # export VOKRA_RNNOISE_V02_PITCH_REFERENCE=~/rnnoise-v02-pitch.csv
//! ```
//!
//! # Numeric parity contract
//!
//! The network check consumes four sequential 65-feature frames and compares
//! 32 gains plus VAD against a fixture generated by compiling
//! `rnnoise_v02_network_reference.c` with the unmodified Xiph v0.2 sources.
//! The network bound is `2e-5` max absolute error. The waveform fixture is
//! generated by `rnnoise_v02_waveform_reference.c`, which calls Xiph's public
//! `rnnoise_process_frame` over 16 deterministic frames. It independently
//! covers the high-pass, 32-band/65-feature frontend, pitch downsample and
//! `remove_doubling`, real network, delayed-spectrum gains, and OLA synthesis.
//! Xiph's scalar KISS FFT and Vokra's native real FFT use different butterfly
//! factorizations. Their frontend features differ by about `2e-5`; the trained
//! recurrent network amplifies that into the measured waveform bounds below.

use std::env;
use std::path::Path;

use vokra_core::engines::DenoiseEngine;
use vokra_models::rnnoise::{
    FRAME_SIZE, N_BANDS as V02_N_BANDS, N_FEATURES as V02_N_FEATURES, RnnoiseNetworkState,
    RnnoiseV02, SAMPLE_RATE,
};

/// Env var the owner sets to point the gated harness at a real RNNoise
/// v0.2 GGUF. Absent = skip cleanly (never a fabricated pass). Present =
/// binding: every downstream check hard-fails on any error.
const GGUF_ENV: &str = "VOKRA_RNNOISE_V02_REAL_GGUF";

// ---------------------------------------------------------------------------
